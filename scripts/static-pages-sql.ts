/**
 * Writes prisma/migrations/20261118010000_static_pages/migration.sql from the
 * starter content in prisma/static-pages/content.ts.
 *
 * Run once while developing (npx tsx scripts/static-pages-sql.ts). The
 * migration file is then committed and must never be changed afterwards:
 * deployed databases record it as applied.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { STARTER_PAGES } from "../prisma/static-pages/content";
import { markdownToBody } from "../src/lib/content/markdown";

const TAG = "$page$";
const q = (s: string) => {
  if (s.includes(TAG)) throw new Error("content contains the quote tag");
  return `${TAG}${s}${TAG}`;
};

const out: string[] = [
  `-- Static pages: About, Contact, Privacy policy, Terms and conditions, Editorial policy.
-- Additive only: two new tables, plus the five pages as unpublished drafts.
-- Generated by scripts/static-pages-sql.ts. Do not edit after deployment.

-- CreateTable
CREATE TABLE "StaticPage" (
    "id" TEXT NOT NULL,
    "key" TEXT NOT NULL,
    "slug" TEXT NOT NULL,
    "sortOrder" INTEGER NOT NULL DEFAULT 0,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "StaticPage_pkey" PRIMARY KEY ("id")
);

-- CreateTable
CREATE TABLE "StaticPageTranslation" (
    "id" TEXT NOT NULL,
    "pageId" TEXT NOT NULL,
    "locale" "Locale" NOT NULL,
    "title" TEXT NOT NULL DEFAULT '',
    "body" JSONB NOT NULL,
    "seoTitle" TEXT NOT NULL DEFAULT '',
    "metaDescription" TEXT NOT NULL DEFAULT '',
    "publishedTitle" TEXT,
    "publishedBody" JSONB,
    "publishedSeoTitle" TEXT,
    "publishedMetaDescription" TEXT,
    "isPublished" BOOLEAN NOT NULL DEFAULT false,
    "publishedAt" TIMESTAMP(3),
    "updatedAt" TIMESTAMP(3) NOT NULL,
    "updatedById" TEXT,

    CONSTRAINT "StaticPageTranslation_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE UNIQUE INDEX "StaticPage_key_key" ON "StaticPage"("key");

-- CreateIndex
CREATE UNIQUE INDEX "StaticPage_slug_key" ON "StaticPage"("slug");

-- CreateIndex
CREATE UNIQUE INDEX "StaticPageTranslation_pageId_locale_key" ON "StaticPageTranslation"("pageId", "locale");

-- AddForeignKey
ALTER TABLE "StaticPageTranslation" ADD CONSTRAINT "StaticPageTranslation_pageId_fkey" FOREIGN KEY ("pageId") REFERENCES "StaticPage"("id") ON DELETE CASCADE ON UPDATE CASCADE;

-- AddForeignKey
ALTER TABLE "StaticPageTranslation" ADD CONSTRAINT "StaticPageTranslation_updatedById_fkey" FOREIGN KEY ("updatedById") REFERENCES "Admin"("id") ON DELETE SET NULL ON UPDATE CASCADE;

-- Starter pages (drafts; nothing is visible to readers until an editor publishes it)`,
];

for (const p of STARTER_PAGES) {
  const pageId = `static_${p.key}`;
  out.push(`INSERT INTO "StaticPage" ("id", "key", "slug", "sortOrder") VALUES ('${pageId}', '${p.key}', '${p.slug}', ${p.sortOrder}) ON CONFLICT DO NOTHING;`);
  for (const locale of ["si", "en"] as const) {
    const c = p[locale];
    const body = JSON.stringify(markdownToBody(c.body));
    out.push(
      `INSERT INTO "StaticPageTranslation" ("id", "pageId", "locale", "title", "body", "metaDescription", "updatedAt") VALUES ('${pageId}_${locale}', '${pageId}', '${locale}', ${q(c.title)}, ${q(body)}::jsonb, ${q(c.metaDescription)}, CURRENT_TIMESTAMP) ON CONFLICT DO NOTHING;`,
    );
  }
}

const dir = "prisma/migrations/20261118010000_static_pages";
mkdirSync(dir, { recursive: true });
writeFileSync(`${dir}/migration.sql`, out.join("\n") + "\n");
console.log(`Wrote ${dir}/migration.sql`);
